/** pg advisory-lock key reserved for the reorder check (any constant unique to this job). */
export const REORDER_LOCK_KEY = 72_410_031

export type ReorderKind = 'cloth' | 'accessory'

export type ReorderTrigger =
  | 'manual'
  | 'alerts'
  | 'order_created'
  | 'order_item_fabric_changed'
  | 'stock_adjusted'
  | 'inventory_edited'
  | 'purchase_order_changed'

const TRIGGER_LABELS: Record<ReorderTrigger, string> = {
  purchase_order_changed: 'purchase order change',
  manual: 'manual check',
  alerts: 'scheduled alert check',
  order_created: 'new order',
  order_item_fabric_changed: 'fabric change',
  stock_adjusted: 'stock adjustment',
  inventory_edited: 'inventory edit',
}

export interface ReorderItem {
  kind: ReorderKind
  id: string
  sku: string
  name: string
  /** PO line name derived from the item (lib/purchase-order-items) */
  lineName: string
  currentStock: number
  reserved: number
  minimum: number
  reorderQuantity: number | null
  /** Only an active supplier counts; inactive or missing → null */
  supplierId: string | null
  supplierName: string | null
  /** pricePerMeter (cloth) or pricePerUnit (accessory) */
  itemPrice: number
}

export interface OpenPOLine {
  status: string
  clothInventoryId: string | null
  accessoryInventoryId: string | null
  orderedQuantity: number
  receivedQuantity: number
}

export interface SupplierPriceRow {
  supplierId: string
  clothInventoryId: string
  pricePerMeter: number
  effectiveFrom: Date
  effectiveTo: Date | null
  active: boolean
}

export interface ReorderInput {
  items: ReorderItem[]
  openLines: OpenPOLine[]
  supplierPrices?: SupplierPriceRow[]
  now?: Date
}

export interface ReorderPosition {
  kind: ReorderKind
  id: string
  sku: string
  name: string
  lineName: string
  itemType: POItemType
  unit: 'meters' | 'pieces'
  available: number
  onOrder: number
  /** The part of onOrder on purchase orders not yet approved */
  awaitingApproval: number
  minimum: number
  reorderQuantity: number | null
  /** Needs a reorder alert: an approval still counts as not reordered */
  needsReorder: boolean
  /** Quantity still to put on a PO (whole meters / units); 0 when not needed or when POs awaiting approval cover it */
  suggestedQuantity: number
  supplierId: string | null
  supplierName: string | null
  unitPrice: number
  priceSource: 'supplier' | 'item'
  severity: AlertSeverity
}

export type ReorderNeed = ReorderPosition & { needsReorder: true }

export const itemKey = (kind: ReorderKind, id: string) => `${kind}:${id}`

const round3 = roundMeters
const EPSILON = 1e-9

/** Current price for a fabric from a supplier: active, effective now, latest effectiveFrom wins. */
export function pickSupplierPrice(
  prices: SupplierPriceRow[],
  clothInventoryId: string,
  supplierId: string | null,
  now: Date = new Date()
): number | null {
  if (!supplierId) return null
  let best: SupplierPriceRow | null = null
  for (const p of prices) {
    if (!p.active || p.clothInventoryId !== clothInventoryId || p.supplierId !== supplierId) continue
    if (p.effectiveFrom.getTime() > now.getTime()) continue
    if (p.effectiveTo && p.effectiveTo.getTime() < now.getTime()) continue
    if (!best || p.effectiveFrom.getTime() > best.effectiveFrom.getTime()) best = p
  }
  return best ? best.pricePerMeter : null
}

/** Outstanding quantity per item on linked lines of POs in one of `statuses`. */
function outstandingByItem(lines: OpenPOLine[], statuses: readonly string[]): Map<string, number> {
  const wanted = new Set<string>(statuses)
  const totals = new Map<string, number>()
  for (const line of lines) {
    if (!wanted.has(line.status)) continue
    const key = line.clothInventoryId
      ? itemKey('cloth', line.clothInventoryId)
      : line.accessoryInventoryId
        ? itemKey('accessory', line.accessoryInventoryId)
        : null
    if (!key) continue
    const outstanding = Math.max(0, line.orderedQuantity - line.receivedQuantity)
    totals.set(key, round3((totals.get(key) ?? 0) + outstanding))
  }
  return totals
}

/** Outstanding quantity per item across open POs (linked lines only). */
export function computeOnOrder(lines: OpenPOLine[]): Map<string, number> {
  return outstandingByItem(lines, OPEN_PO_STATUSES)
}

/** The part of computeOnOrder on purchase orders not yet approved. */
export function computeAwaitingApproval(lines: OpenPOLine[]): Map<string, number> {
  return outstandingByItem(lines, UNAPPROVED_PO_STATUSES)
}

/** Severity by physical shortfall: out of stock → CRITICAL, at or below half the minimum → HIGH, else MEDIUM. */
export function reorderSeverity(available: number, minimum: number): AlertSeverity {
  if (available <= 0) return 'CRITICAL'
  if (available <= minimum * 0.5) return 'HIGH'
  return 'MEDIUM'
}

/** Whole meters (cloth) / units (accessories), always rounded up. */
function wholeQuantity(quantity: number): number {
  return Math.max(0, Math.ceil(round3(quantity) - EPSILON))
}

/**
 * The reorder rule for one item. `onOrder` is everything outstanding on open POs; `awaitingApproval`
 * is the part of it on POs not yet approved.
 *   needed   when available + approved on-order ≤ minimum — a draft doesn't settle it until approved
 *   quantity = (reorderQuantity, else enough to reach twice the minimum after approved on-order)
 *              − what already awaits approval, rounded up to a whole meter / unit; 0 = only an approval is due
 */
export function reorderSuggestion(p: {
  available: number
  onOrder: number
  awaitingApproval?: number
  minimum: number
  reorderQuantity: number | null
}): { needsReorder: boolean; quantity: number } {
  const pending = Math.min(p.awaitingApproval ?? 0, p.onOrder)
  const approved = p.onOrder - pending
  const needsReorder = round3(p.available + approved) <= p.minimum + EPSILON
  const reorderQuantity = p.reorderQuantity && p.reorderQuantity > 0 ? p.reorderQuantity : null
  const target = reorderQuantity ?? Math.max(0, 2 * p.minimum - p.available - approved)
  return { needsReorder, quantity: needsReorder ? wholeQuantity(Math.max(0, target - pending)) : 0 }
}

/**
 * Stock position and suggested order for every item.
 * `priceSupplierId` prices fabric from that supplier instead of each item's own supplier
 * (the PO picker passes the PO's supplier).
 */
export function computeReorderPositions(
  input: ReorderInput,
  opts: { priceSupplierId?: string | null } = {}
): ReorderPosition[] {
  const now = input.now ?? new Date()
  const onOrderMap = computeOnOrder(input.openLines)
  const awaitingMap = computeAwaitingApproval(input.openLines)
  const prices = input.supplierPrices ?? []

  return input.items.map((item) => {
    const isCloth = item.kind === 'cloth'
    const available = isCloth ? round3(item.currentStock - item.reserved) : item.currentStock - item.reserved
    const onOrder = onOrderMap.get(itemKey(item.kind, item.id)) ?? 0
    const awaitingApproval = awaitingMap.get(itemKey(item.kind, item.id)) ?? 0
    const reorderQuantity = item.reorderQuantity && item.reorderQuantity > 0 ? item.reorderQuantity : null
    const { needsReorder, quantity: suggestedQuantity } = reorderSuggestion({
      available,
      onOrder,
      awaitingApproval,
      minimum: item.minimum,
      reorderQuantity,
    })

    const supplierPrice = isCloth
      ? pickSupplierPrice(prices, item.id, opts.priceSupplierId ?? item.supplierId, now)
      : null

    return {
      kind: item.kind,
      id: item.id,
      sku: item.sku,
      name: item.name,
      lineName: item.lineName,
      itemType: isCloth ? 'CLOTH' : 'ACCESSORY',
      unit: isCloth ? PO_LINE_UNIT.CLOTH : PO_LINE_UNIT.ACCESSORY,
      available,
      onOrder,
      minimum: item.minimum,
      reorderQuantity,
      awaitingApproval,
      needsReorder,
      suggestedQuantity,
      supplierId: item.supplierId,
      supplierName: item.supplierName,
      unitPrice: supplierPrice ?? item.itemPrice,
      priceSource: supplierPrice !== null ? 'supplier' : 'item',
      severity: reorderSeverity(available, item.minimum),
    }
  })
}

/**
 * Items that need a reorder (each keeps an alert). suggestedQuantity is 0 when purchase orders awaiting
 * approval already cover the item — then only the approval is outstanding and nothing more is drafted.
 */
export function computeReorderNeeds(input: ReorderInput): ReorderNeed[] {
  return computeReorderPositions(input).filter((p): p is ReorderNeed => p.needsReorder)
}

